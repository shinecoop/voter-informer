"""Convert us-atlas@3.0.1 states-albers-10m.json to bundled SVG paths.

Usage: python3 scripts/generate-map.py /path/to/states-albers-10m.json
No network requests or third-party Python packages are required.
"""
import hashlib
import json
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_bytes()
topology = json.loads(source)
scale = topology["transform"]["scale"]
translate = topology["transform"]["translate"]


def simplify(points, tolerance=0.4):
    if len(points) < 3:
        return points
    start, end = points[0], points[-1]
    dx, dy = end[0] - start[0], end[1] - start[1]
    length = dx * dx + dy * dy
    furthest, distance = 0, 0
    for index, point in enumerate(points[1:-1], 1):
        t = max(0, min(1, ((point[0] - start[0]) * dx + (point[1] - start[1]) * dy) / length)) if length else 0
        squared = (point[0] - start[0] - t * dx) ** 2 + (point[1] - start[1] - t * dy) ** 2
        if squared > distance:
            furthest, distance = index, squared
    if distance <= tolerance * tolerance:
        return [start, end]
    return simplify(points[:furthest + 1])[:-1] + simplify(points[furthest:])


arcs = []
for arc in topology["arcs"]:
    x = y = 0
    points = []
    for dx, dy in arc:
        x += dx
        y += dy
        points.append((x * scale[0] + translate[0], y * scale[1] + translate[1]))
    # Simplify shared arcs once to preserve matching state boundaries.
    arcs.append(simplify(points))

states = []
for geometry in topology["objects"]["states"]["geometries"]:
    polygons = [geometry["arcs"]] if geometry["type"] == "Polygon" else geometry["arcs"]
    paths = []
    for polygon in polygons:
        for ring in polygon:
            points = []
            for index in ring:
                arc = arcs[index] if index >= 0 else list(reversed(arcs[~index]))
                points.extend(arc if not points else arc[1:])
            # One decimal is finer than a display pixel at typical viewport sizes.
            pairs = [f"{x:.1f},{y:.1f}" for x, y in points]
            paths.append("M" + "L".join(pairs) + "Z")
    states.append({"id": geometry["id"], "name": geometry["properties"]["name"], "d": "".join(paths)})
states.sort(key=lambda state: state["name"])
output = Path(__file__).resolve().parents[1] / "src/components/us-map-paths.ts"
output.write_text(
    "// Generated by scripts/generate-map.py; do not edit paths by hand.\n"
    "// us-atlas@3.0.1, 2017 Census boundaries. See docs/map-source.md.\n"
    f"// Input SHA-256: {hashlib.sha256(source).hexdigest()}\n"
    "export const states = " + json.dumps(states, separators=(",", ":")) + " as const;\n"
)
print(f"Generated {len(states)} shapes, {output.stat().st_size:,} bytes")
