"""Project Census CD120 Colorado GeoJSON into the bundled Albers USA SVG.

Usage: python3 scripts/generate-colorado-districts.py /path/to/colorado-cd120.geojson
Uses only Python's standard library; see docs/map-source.md for the source query.
"""
import hashlib
import json
import math
from pathlib import Path
import sys


def albers_raw(longitude, latitude):
    phi0, phi1 = math.radians(29.5), math.radians(45.5)
    n = (math.sin(phi0) + math.sin(phi1)) / 2
    c = 1 + math.sin(phi0) * (2 * n - math.sin(phi0))
    radius = math.sqrt(c - 2 * n * math.sin(math.radians(latitude))) / n
    theta = n * math.radians(longitude)
    return radius * math.sin(theta), math.sqrt(c) / n - radius * math.cos(theta)


# Match us-atlas's d3.geoAlbersUsa(): lower-48 Albers projection,
# rotate([96, 0]), center([-0.6, 38.7]), scale(1300), translate([487.5, 305]).
center_x, center_y = albers_raw(-0.6, 38.7)


def project(longitude, latitude):
    x, y = albers_raw(longitude + 96, latitude)
    return 487.5 + 1300 * (x - center_x), 305 - 1300 * (y - center_y)


source = Path(sys.argv[1]).read_bytes()
collection = json.loads(source)
features = collection["features"]
if len(features) != 8 or {f["properties"]["GEOID"] for f in features} != {f"08{n:02d}" for n in range(1, 9)}:
    raise ValueError("Expected exactly Colorado congressional districts 1 through 8")

districts = []
for feature in features:
    properties = feature["properties"]
    if properties["STATE"] != "08" or properties["CDSESSN"] != "120":
        raise ValueError("Only Colorado's 120th congressional districts are supported")
    geometry = feature["geometry"]
    if geometry["type"] not in {"Polygon", "MultiPolygon"}:
        raise ValueError("Expected polygon geometry")
    polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
    paths = []
    for polygon in polygons:
        for ring in polygon:
            points = []
            for longitude, latitude in ring:
                if not (-110 < longitude < -101 and 36 < latitude < 42):
                    raise ValueError("Coordinate is outside Colorado's expected extent")
                x, y = project(longitude, latitude)
                points.append(f"{x:.3f},{y:.3f}")
            paths.append("M" + "L".join(points) + "Z")
    districts.append({
        "id": properties["GEOID"],
        "name": f"Colorado congressional district {int(properties['CD120'])}",
        "d": "".join(paths),
    })
districts.sort(key=lambda district: district["id"])
output = Path(__file__).resolve().parents[1] / "src/components/colorado-district-paths.ts"
output.write_text(
    "// Generated by scripts/generate-colorado-districts.py.\n"
    "// Source: U.S. Census Bureau, CD120, January 1, 2026. See docs/map-source.md.\n"
    f"// Input SHA-256: {hashlib.sha256(source).hexdigest()}\n"
    "export const districts = " + json.dumps(districts, separators=(",", ":")) + " as const;\n"
)
print(f"Generated {len(districts)} districts; {output.stat().st_size:,} bytes")
